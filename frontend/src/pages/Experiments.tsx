import { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'
import { api, type ExperimentsListResponse } from '../api/client'
import { UnavailableNotice } from '../components/UnavailableNotice'

function fmt(value: number | null | undefined, digits = 3): string {
  return value === null || value === undefined ? 'N/A' : value.toFixed(digits)
}

export function Experiments() {
  const [data, setData] = useState<ExperimentsListResponse | null>(null)
  const [error, setError] = useState(false)

  useEffect(() => {
    api
      .experiments()
      .then(setData)
      .catch(() => setError(true))
  }, [])

  return (
    <div className="space-y-8">
      <div>
        <h2 className="text-sm font-semibold uppercase tracking-wide text-slate-400">Experiment comparison</h2>
        <p className="mt-2 max-w-3xl text-sm text-slate-400">
          Research question: after removing features that directly encode (or are a NASA-side derived transform
          of) the PHA classification, how much predictive signal remains in the object's other orbital/physical
          characteristics? See <code>docs/FEATURE_AUDIT.md</code>. Every number below, when present, is read from{' '}
          <code>results/experiments/&lt;experiment&gt;/&lt;model&gt;/*.json</code>, generated by{' '}
          <code>python -m src.experiments.run_all</code> — never hand-typed.
        </p>
      </div>

      {error && <UnavailableNotice detail="Could not reach the backend." />}
      {!data && !error && <p className="text-sm text-slate-500">Loading…</p>}
      {data?.status === 'unavailable' && (
        <UnavailableNotice detail="No experiment has been executed yet. Run `python -m src.experiments.run_all` against a real ingested dataset." />
      )}

      {data?.status === 'ok' &&
        Object.entries(data.experiments).map(([key, exp]) => (
          <section key={key} className="space-y-2">
            <div>
              <h3 className="text-sm font-medium text-slate-100">{exp.display_name}</h3>
              <p className="text-xs text-slate-500">{exp.purpose}</p>
            </div>
            <div className="overflow-hidden rounded-lg border border-white/10">
              <table className="w-full text-left text-xs">
                <thead className="bg-white/[0.04] text-slate-400">
                  <tr>
                    <th className="px-3 py-2">Model</th>
                    <th className="px-3 py-2">CV F1 (mean ± std)</th>
                    <th className="px-3 py-2">Test F1</th>
                    <th className="px-3 py-2">Precision</th>
                    <th className="px-3 py-2">Recall</th>
                    <th className="px-3 py-2">ROC-AUC</th>
                    <th className="px-3 py-2">PR-AUC</th>
                    <th className="px-3 py-2"></th>
                  </tr>
                </thead>
                <tbody>
                  {Object.entries(exp.models).map(([modelName, m]) => (
                    <tr key={modelName} className="border-t border-white/5">
                      <td className="px-3 py-2 font-mono">{modelName}</td>
                      {!m.executed ? (
                        <td colSpan={6} className="px-3 py-2 text-slate-600">
                          Not yet executed
                        </td>
                      ) : (
                        <>
                          <td className="px-3 py-2">
                            {fmt(m.cv_f1_mean)} ± {fmt(m.cv_f1_std)}
                          </td>
                          <td className="px-3 py-2">{fmt(m.test_f1)}</td>
                          <td className="px-3 py-2">{fmt(m.test_precision)}</td>
                          <td className="px-3 py-2">{fmt(m.test_recall)}</td>
                          <td className="px-3 py-2">{fmt(m.test_roc_auc)}</td>
                          <td className="px-3 py-2">{fmt(m.test_pr_auc)}</td>
                        </>
                      )}
                      <td className="px-3 py-2">
                        {m.executed && (
                          <Link to={`/experiments/${key}/${modelName}`} className="text-sky-400 hover:underline">
                            Details →
                          </Link>
                        )}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </section>
        ))}
    </div>
  )
}
